/// Maps a BCP-47 language code (e.g. a device locale's `languageCode`, like
/// `en`, `ar`, `fr`) back to a supported display language name — a key of
/// [languageCodes]. Returns null when the code isn't supported. A few common
/// aliases are handled where the device code differs from the stored BCP-47
/// tag (e.g. `zh` → 'Chinese, Mandarin').
String? languageFromBcp47Code(String code) {
  final normalized = code.split(RegExp(r'[-_]')).first.toLowerCase();
  for (final entry in languageBcp47Codes.entries) {
    if (entry.value == normalized) return entry.key;
  }
  const aliases = <String, String>{
    'zh': 'Chinese, Mandarin',
    'no': 'Bokmål',
  };
  return aliases[normalized];
}

String getLanguageDisplayName(String language) {
  final code = languageCodes[language];
  if (code == null) return language;
  final count = languageCodes.values.where((c) => c == code).length;
  if (count > 1) {
    final country = countryNames[code] ?? code;
    return '$country ($language)';
  }
  return language;
}
